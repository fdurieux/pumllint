"""Build the handover set's generated documents from the kit (stdlib only).

    python build.py                 # REQUIREMENTS.md, DECISIONS.md, TRACE.md
    python build.py --plantuml P    # also render ../kit/uml/*.puml to diagrams/*.svg
                                    # with the jar at P (built-in layout, no Graphviz)
    python build.py --zip OUT.zip   # also pack kit/ + handover/ as one archive
    python build.py --check         # exit 1 if a generated file is out of date

Sources: ../kit/requirements.json, ../kit/contracts/dmn/*.dmn, the pumllint
trace report over ../kit (run here with `python -m pumllint`, so pumllint
must be importable: `pip install pumllint` or run from the pumllint checkout
with PYTHONPATH set). Hand-written files are never touched.
"""
import json
import os
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
KIT = HERE.parent / "kit"
NS = {"dmn": "https://www.omg.org/spec/DMN/20191111/MODEL/"}
KINDS = [("contract", "Contracts: shapes, files, grammars"),
         ("arithmetic", "Arithmetic: adjustment, factors, measurements"),
         ("ritual", "Rituals: the sync, its legs, windows and gates"),
         ("verdict", "Verdicts: what status reports and how"),
         ("refusal", "Refusals: every error the user can meet"),
         ("cli", "Command line: surface, output, exit codes"),
         ("chain", "The daily chain script")]
GENERATED = "<!-- generated by handover/build.py from ../kit — do not edit by hand -->\n"


def trace_report():
    env = dict(os.environ)
    env["PYTHONPATH"] = str(HERE.parents[1]) + os.pathsep + env.get("PYTHONPATH", "")
    out = subprocess.run([sys.executable, "-m", "pumllint", "trace", "uml", "--requirements", "requirements.json",
                          "--features", "features", "-f", "json"], cwd=KIT, env=env, capture_output=True, text=True)
    if not out.stdout.strip():
        sys.exit("pumllint trace produced no report: " + out.stderr[-500:])
    return json.loads(out.stdout)


def md_escape(s):
    return s.replace("|", "\\|").replace("\n", " ")


def requirements_md(reqs, trace):
    by_id = {r["id"]: r for r in trace["requirements"]}
    lines = [GENERATED, "# Requirements, by kind\n",
             f"{len(reqs)} atomic requirements from `../kit/requirements.json`, each with the diagram that "
             "realises it and the scenarios that verify it (from `pumllint trace`). Ids are stable; a "
             "statement is the contract, the rationale says why it reads that way. `basis` records how the "
             "requirement was derived when the kit was written: `logic` from the code's control flow, "
             "`prose` from a comment or docstring, `both`.\n"]
    for kind, title in KINDS:
        items = [r for r in reqs if r["kind"] == kind]
        lines.append(f"\n## {title} ({len(items)})\n")
        for r in items:
            t = by_id.get(r["id"], {})
            dia = ", ".join(sorted({c["name"] for c in t.get("coveredBy", [])})) or "—"
            sc = sorted({f"{Path(v['file']).name}: {v.get('scenario') or '(file-level)'}" for v in t.get("verifiedBy", [])})
            lines.append(f"\n### {r['id']} · {r['kind']} · basis {r.get('basis', '?')}\n")
            lines.append(r["statement"].strip() + "\n")
            if r.get("rationale"):
                lines.append(f"\n*Why:* {r['rationale'].strip()}\n")
            lines.append(f"\n*Realised by:* {dia}  \n*Verified by:* " + ("; ".join(sc) if sc else "—") + "\n")
    return "".join(l if l.endswith("\n") else l + "\n" for l in lines)


def decisions_md():
    lines = [GENERATED, "# Decision tables\n",
             "The kit's DMN 1.3 tables (`../kit/contracts/dmn/*.dmn`), rendered. Hit policy UNIQUE: exactly one "
             "rule matches any input. `-` means any value. Every rule names the requirement or contract line it "
             "encodes; `harness/dmn_check.py` proves the tables complete, non-overlapping and typed, and "
             "`features/decisions.feature` exercises every reachable rule.\n"]
    for f in sorted((KIT / "contracts" / "dmn").glob("*.dmn")):
        root = ET.parse(f).getroot()
        for dec in root.findall("dmn:decision", NS):
            dt = dec.find("dmn:decisionTable", NS)
            desc = dec.find("dmn:description", NS)
            inputs = [(i.get("label"), i.find("dmn:inputExpression", NS).get("typeRef"),
                       (i.find("dmn:inputValues/dmn:text", NS).text if i.find("dmn:inputValues/dmn:text", NS) is not None else ""))
                      for i in dt.findall("dmn:input", NS)]
            outputs = [(o.get("label"), (o.find("dmn:outputValues/dmn:text", NS).text if o.find("dmn:outputValues/dmn:text", NS) is not None else ""))
                       for o in dt.findall("dmn:output", NS)]
            lines.append(f"\n## {dec.get('name')} (`{f.name}`)\n")
            if desc is not None and desc.text:
                lines.append(desc.text.strip() + "\n")
            lines.append("\nInputs: " + "; ".join(f"`{l}` ({t}{': ' + v if v else ''})" for l, t, v in inputs) + "  \n")
            lines.append("Outputs: " + "; ".join(f"`{l}`{' ∈ ' + v if v else ''}" for l, v in outputs) + "\n\n")
            head = ["rule"] + [l for l, _, _ in inputs] + ["→"] + [l for l, _ in outputs] + ["source"]
            lines.append("| " + " | ".join(head) + " |\n|" + "---|" * len(head) + "\n")
            for r in dt.findall("dmn:rule", NS):
                rid = r.get("id").split("_r")[-1]
                ins = [md_escape(e.find("dmn:text", NS).text or "-") for e in r.findall("dmn:inputEntry", NS)]
                outs = [md_escape((e.find("dmn:text", NS).text or "").replace('"', "")) for e in r.findall("dmn:outputEntry", NS)]
                d = r.find("dmn:description", NS)
                lines.append("| r" + rid + " | " + " | ".join(f"`{i}`" for i in ins) + " | | " + " | ".join(outs) + " | " + md_escape(d.text if d is not None else "") + " |\n")
    return "".join(lines)


def trace_md(trace):
    s = trace["summary"]
    lines = [GENERATED, "# Traceability\n",
             "What `pumllint trace` reports over the kit: every requirement realised by a diagram and verified by a "
             "scenario. Regenerate after any change to `uml/`, `features/` or `requirements.json`.\n",
             "\n| measure | value |\n|---|---|\n"]
    for k in sorted(s):
        v = s[k]
        if not isinstance(v, (dict, list)):
            lines.append(f"| {k} | {v} |\n")
    by_dia, by_feat = {}, {}
    for r in trace["requirements"]:
        for c in r.get("coveredBy", []):
            by_dia.setdefault(c["name"], set()).add(r["id"])
        for v in r.get("verifiedBy", []):
            by_feat.setdefault(Path(v["file"]).name, {}).setdefault(v.get("scenario") or "(file-level)", set()).add(r["id"])
    lines.append("\n## Diagram → requirements\n")
    for d in sorted(by_dia):
        ids = sorted(by_dia[d])
        lines.append(f"\n**{d}** ({len(ids)}): " + ", ".join(ids) + "\n")
    lines.append("\n## Feature → scenario → requirements\n")
    for f in sorted(by_feat):
        n = sum(len(v) for v in by_feat[f].values())
        lines.append(f"\n### {f} ({len(by_feat[f])} scenarios)\n\n")
        for sc in sorted(by_feat[f]):
            lines.append(f"- {sc}: " + ", ".join(sorted(by_feat[f][sc])) + "\n")
    for key, title in [("unknownReferences", "Diagram references matching no requirement"),
                       ("unlinkedDiagrams", "Diagrams referencing no requirement"),
                       ("unknownFeatureReferences", "Feature references matching no requirement"),
                       ("unlinkedFeatures", "Feature files referencing no requirement"),
                       ("unlinkedScenarios", "Scenarios no reference reaches")]:
        v = trace.get(key) or []
        lines.append(f"\n## {title}\n\n" + ("none\n" if not v else "\n".join(f"- {json.dumps(x)}" for x in v) + "\n"))
    return "".join(lines)


def render(jar):
    out = HERE / "diagrams"
    out.mkdir(exist_ok=True)
    cmd = ["java", "-Djava.awt.headless=true", "-jar", str(jar), "-tsvg", "-nometadata", "-Playout=smetana",
           "-o", str(out)] + [str(p) for p in sorted((KIT / "uml").glob("*.puml"))]
    subprocess.run(cmd, check=True, capture_output=True)
    for svg in out.glob("*.svg"):
        text = svg.read_text(encoding="utf-8")
        assert "<svg" in text, svg
    print("rendered", sorted(p.name for p in out.glob("*.svg")))


def pack(target):
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as z:
        for base, arc in ((KIT, "kit"), (HERE, "handover")):
            for p in sorted(base.rglob("*")):
                if p.is_file() and "__pycache__" not in p.parts and not p.name.endswith(".pyc"):
                    z.write(p, f"{arc}/{p.relative_to(base).as_posix()}")
        harness = HERE.parent / "harness"
        for name in ("dmn_check.py", "dmn_coverage.py", "glossary_check.py", "fixturelib.py", "invariants/test_properties.py", "invariants/README.md"):
            z.write(harness / name, f"harness/{name}")
        # the knowledge-transfer plan and the unrealised-code register it uses as an instrument
        for rel in ("knowledge-transfer/DOMINIQUE-CASE.md", "results/coverage/UNREALISED.md", "results/coverage/coverage.json"):
            src = HERE.parent / rel
            if src.exists():
                z.write(src, rel)
    print("packed", target, zipfile.ZipFile(target).namelist().__len__(), "files")


def main(argv):
    reqs = json.load(open(KIT / "requirements.json", encoding="utf-8"))
    trace = trace_report()
    docs = {"REQUIREMENTS.md": requirements_md(reqs, trace), "DECISIONS.md": decisions_md(), "TRACE.md": trace_md(trace)}
    if "--check" in argv:
        stale = [n for n, t in docs.items() if not (HERE / n).exists() or (HERE / n).read_text(encoding="utf-8") != t]
        print("stale:", stale or "none")
        return 1 if stale else 0
    for n, t in docs.items():
        (HERE / n).write_text(t, encoding="utf-8")
    print("wrote", list(docs))
    if "--plantuml" in argv:
        render(Path(argv[argv.index("--plantuml") + 1]))
    if "--zip" in argv:
        pack(Path(argv[argv.index("--zip") + 1]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

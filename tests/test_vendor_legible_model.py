"""tools/vendor_legible_model.py: the Legible model copied from a checkout of the site at a
commit, SOURCE.md written from git's answers and the file's own version field. Exercised on a
throwaway git repository, then held to the real copy's note."""
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import vendor_legible_model as vm  # noqa: E402


def _git(repo, *args):
    return subprocess.run(["git", "-C", str(repo), "-c", "user.name=t", "-c", "user.email=t@example.invalid",
                           "-c", "commit.gpgsign=false", *args], check=True, capture_output=True, text=True).stdout.strip()


def _model(repo: Path, version: str, edges: int):
    (repo / "model").mkdir(exist_ok=True)
    (repo / "model" / "model.json").write_text(json.dumps({"title": "t", "version": version, "date": "2026-01-0" + version[-1],
                                                            "nodes": [{"id": "n1"}], "edges": [{"id": f"e{i}"} for i in range(edges)]}),
                                               encoding="utf-8")
    (repo / "model" / "model-data.py").write_text("# source\n", encoding="utf-8")


def test_vendor_model_copies_the_file_and_writes_the_note_from_its_version():
    with tempfile.TemporaryDirectory() as tmp:
        repo, dest = Path(tmp) / "site", Path(tmp) / "dest"
        repo.mkdir()
        _git(repo, "init", "-q")
        _git(repo, "remote", "add", "origin", "https://github.com/fdurieux/fdurieux.github.io.git")
        _model(repo, "0.3", 2)
        _git(repo, "add", "-A")
        _git(repo, "commit", "-q", "-m", "model v0.3")
        lines = []
        r = vm.vendor(repo, dest, copied="2026-02-02", out=lines.append)   # no tag needed: the site has none
        commit = _git(repo, "rev-parse", "HEAD")
        assert r["version"] == "0.3" and r["dated"] == "2026-01-03" and r["commit"] == commit and r["tag"] == ""
        assert (dest / "model.json").read_bytes() == (repo / "model" / "model.json").read_bytes()
        assert not (dest / "model-data.py").exists(), "only model.json is copied"
        note = (dest / "SOURCE.md").read_text(encoding="utf-8")
        assert note.startswith("# Vendored copy of the Legible systemic impact model, v0.3\n")
        assert "| version | 0.3, dated 2026-01-03 (`\"version\": \"0.3\"` in the file) |" in note
        assert f"| commit | `{commit}` — \"model v0.3\", " in note and "| tag |" not in note
        assert f"| sha256 of `model.json` | `{r['digest']}` |" in note
        assert "| copied | 2026-02-02, byte for byte, generated by `tools/vendor_legible_model.py`" in note
        assert "## Earlier copies" not in note
        assert lines[0].endswith("model v0.3, 1 nodes, 2 edges; model.json changed")

        # A new version at a tagged commit: the tag row appears, the first copy becomes an earlier one.
        _model(repo, "0.4", 3)
        _git(repo, "add", "-A")
        _git(repo, "commit", "-q", "-m", "model v0.4")
        _git(repo, "tag", "v0.4")
        lines.clear()
        dry = vm.vendor(repo, dest, copied="2026-03-03", dry_run=True, out=lines.append)
        assert dry["changed"] and json.loads((dest / "model.json").read_text())["version"] == "0.3", "a dry run writes nothing"
        r2 = vm.vendor(repo, dest, copied="2026-03-03", out=lines.append)
        note = (dest / "SOURCE.md").read_text(encoding="utf-8")
        assert r2["tag"] == "v0.4" and "| tag | `v0.4` |" in note and "| version | 0.4, dated 2026-01-04" in note
        assert f"| `0.3` | `{commit[:7]}` | 2026-02-02 |" in note
        r3 = vm.vendor(repo, dest, copied="2026-03-04", out=lines.append)
        assert not r3["changed"] and (dest / "SOURCE.md").read_text(encoding="utf-8").count("| `0.3` |") == 1


def test_vendor_model_refuses_a_dirty_tree_and_a_file_without_a_version():
    with tempfile.TemporaryDirectory() as tmp:
        repo, dest = Path(tmp) / "site", Path(tmp) / "dest"
        repo.mkdir()
        _git(repo, "init", "-q")
        _model(repo, "0.3", 1)
        (repo / "model" / "model.json").write_text(json.dumps({"title": "no version", "nodes": [], "edges": []}), encoding="utf-8")
        _git(repo, "add", "-A")
        _git(repo, "commit", "-q", "-m", "no version")
        try:
            vm.vendor(repo, dest, out=lambda s: None)
            raise AssertionError("a model without a version field must be refused")
        except SystemExit as e:
            assert "version" in str(e)
        _model(repo, "0.3", 1)
        try:
            vm.vendor(repo, dest, out=lambda s: None)
            raise AssertionError("a dirty tree must be refused")
        except SystemExit as e:
            assert "uncommitted changes" in str(e)


def test_real_model_note_is_the_tools_output_at_the_commit():
    """The shipped model/SOURCE.md is what the tool writes for the vendored commit: the marker,
    the version row the demo test reads, and the digest of the file beside it."""
    import hashlib
    dest = ROOT / "kg_experiment" / "demo" / "model"
    note = (dest / "SOURCE.md").read_text(encoding="utf-8")
    model = json.loads((dest / "model.json").read_text(encoding="utf-8"))
    digest = hashlib.sha256((dest / "model.json").read_bytes()).hexdigest()
    assert vm.MARK in note and re.search(r"^\| version \| 0\.3, dated 2026-10-29", note, re.M)
    assert vm.source_note({"commit": "099a7373e5c7817953709e8a0af45f050fc67a5c", "tag": "", "repo": "fdurieux/fdurieux.github.io",
                           "subject": "Systemic impact model v0.3: review corrections, degradation refinements, knowledge source (#2)",
                           "date": "2026-10-29"}, model["version"], model["date"], digest, "2026-11-01", []) == note
    assert vm.earlier_copies(note) == [], "the first generated note carries no earlier copy: the commit did not change"

"""tools/vendor_register.py: the register copied from a checkout at a tag, SOURCE.md written
from git's answers, a dirty tree and an untagged commit refused. Exercised on a throwaway git
repository built here, then held to the real copy's note."""
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOOL = ROOT / "tools" / "vendor_register.py"
sys.path.insert(0, str(TOOL.parent))
import vendor_register as vr  # noqa: E402


def _git(repo, *args):
    return subprocess.run(["git", "-C", str(repo), "-c", "user.name=t", "-c", "user.email=t@example.invalid",
                           "-c", "commit.gpgsign=false", *args], check=True, capture_output=True, text=True).stdout.strip()


def _mini_register(repo: Path, surcharge: str = "1"):
    for rel, text in {"metamodel/types.toml": "[x]\n", "glossary/glossary.toml": "[terms]\n",
                      "capabilities/CAP-0001.toml": f'id = "CAP-0001"\nsurcharge = {surcharge}\n',
                      "relationships/supports.toml": "[type]\n", "exceptions/EXC-0001.toml": "[e]\n",
                      "mapping/matrix.toml": "[m]\n", "decisions/0001.md": "# one\n",
                      "exports/kit/2026-01-01/MANIFEST.toml": "exported_on = 2026-01-01\n",
                      "tools/register.py": "# r\n", "tools/check_register.py": "# c\n", "tools/impact.py": "# i\n",
                      "products/PRD-0001.toml": "[p]\n", "journeys/JRN-0001.toml": "[j]\n", "processes/PROC-0001.toml": "[p]\n",
                      "applications/APP-0001.toml": "[a]\n", "information/ENT-0001.toml": "[i]\n", "organisation/ORG-0001.toml": "[o]\n",
                      "README.md": "not copied\n", ".github/workflows/ci.yml": "not copied\n"}.items():
        (repo / rel).parent.mkdir(parents=True, exist_ok=True)
        (repo / rel).write_text(text, encoding="utf-8")


def test_vendor_register_copies_a_tagged_checkout_and_writes_source_md():
    with tempfile.TemporaryDirectory() as tmp:
        repo, dest = Path(tmp) / "src", Path(tmp) / "dest"
        repo.mkdir()
        _git(repo, "init", "-q")
        _git(repo, "remote", "add", "origin", "https://github.com/fdurieux/ieam-register.git")
        _mini_register(repo)
        _git(repo, "add", "-A")
        _git(repo, "commit", "-q", "-m", "first slice")
        _git(repo, "tag", "v9.0.0")
        lines = []
        r = vr.vendor(repo, dest, copied="2026-02-02", out=lines.append)
        commit = _git(repo, "rev-parse", "HEAD")
        assert r["tag"] == "v9.0.0" and r["commit"] == commit and r["repo"] == "fdurieux/ieam-register"
        assert len(r["digests"]) == 17 and "README.md" not in r["digests"] and ".github/workflows/ci.yml" not in r["digests"]
        assert r["pinned"] == "2026-01-01", "the pinned date is the newest kit export's"
        assert (dest / "capabilities" / "CAP-0001.toml").read_bytes() == (repo / "capabilities" / "CAP-0001.toml").read_bytes()
        note = (dest / "SOURCE.md").read_text(encoding="utf-8")
        assert f"| commit | `{commit}` — \"first slice\", " in note
        assert re.search(r"^\| tag \| `v9\.0\.0`", note, re.M) and "| files | 17 |" in note
        assert "| copied | 2026-02-02, byte for byte, generated by `tools/vendor_register.py`" in note
        assert "pinned date for the checker | `2026-01-01`" in note
        assert "## Earlier copies" not in note, "a first copy has no earlier one"
        for rel, sha in r["digests"].items():
            assert f"| `{rel}` | `{sha}` |" in note
        assert lines[0].startswith("fdurieux/ieam-register at v9.0.0 (") and "17 files; 17 added, 0 removed, 0 changed" in lines[0]

        # A second tag: one file changed, one removed, one added; the first copy becomes an earlier one.
        (repo / "capabilities" / "CAP-0001.toml").write_text('id = "CAP-0001"\nsurcharge = 2\n', encoding="utf-8")
        (repo / "journeys" / "JRN-0001.toml").unlink()
        (repo / "journeys" / "JRN-0002.toml").write_text("[j2]\n", encoding="utf-8")
        _git(repo, "add", "-A")
        _git(repo, "commit", "-q", "-m", "second slice")
        _git(repo, "tag", "v9.1.0")
        lines.clear()
        dry = vr.vendor(repo, dest, copied="2026-03-03", dry_run=True, out=lines.append)
        assert (dry["added"], dry["removed"], dry["changed"]) == (["journeys/JRN-0002.toml"], ["journeys/JRN-0001.toml"], ["capabilities/CAP-0001.toml"])
        assert (dest / "journeys" / "JRN-0001.toml").exists(), "a dry run writes nothing"
        assert "v9.0.0" in (dest / "SOURCE.md").read_text(encoding="utf-8")
        r2 = vr.vendor(repo, dest, copied="2026-03-03", out=lines.append)
        assert not (dest / "journeys" / "JRN-0001.toml").exists() and (dest / "journeys" / "JRN-0002.toml").exists()
        note = (dest / "SOURCE.md").read_text(encoding="utf-8")
        assert re.search(r"^\| tag \| `v9\.1\.0`", note, re.M)
        assert "journeys/JRN-0001.toml" not in note
        assert f"| `v9.0.0` | `{commit[:7]}` | 2026-02-02 |" in note, "the superseded copy is carried as an earlier one"
        assert r2["digests"]["capabilities/CAP-0001.toml"] != r["digests"]["capabilities/CAP-0001.toml"]

        # A third run at the same tag changes nothing and adds no earlier row.
        r3 = vr.vendor(repo, dest, copied="2026-03-04", out=lines.append)
        assert (r3["added"], r3["removed"], r3["changed"]) == ([], [], [])
        assert (dest / "SOURCE.md").read_text(encoding="utf-8").count("| `v9.0.0` |") == 1


def test_vendor_register_refuses_a_dirty_tree_and_an_untagged_commit():
    with tempfile.TemporaryDirectory() as tmp:
        repo, dest = Path(tmp) / "src", Path(tmp) / "dest"
        repo.mkdir()
        _git(repo, "init", "-q")
        _mini_register(repo)
        _git(repo, "add", "-A")
        _git(repo, "commit", "-q", "-m", "untagged")
        try:
            vr.vendor(repo, dest, out=lambda s: None)
            raise AssertionError("an untagged commit must be refused")
        except SystemExit as e:
            assert "carries no tag" in str(e)
        assert not dest.exists()
        r = vr.vendor(repo, dest, allow_untagged=True, copied="2026-02-02", out=lambda s: None)
        assert r["tag"] == "" and "| tag | none — an untagged commit, copied with `--allow-untagged` |" in r["note"]
        assert r["repo"] == "", "no origin, no repository slug invented"
        (repo / "mapping" / "matrix.toml").write_text("[m]\nchanged = true\n", encoding="utf-8")
        try:
            vr.vendor(repo, dest, allow_untagged=True, out=lambda s: None)
            raise AssertionError("a dirty tree must be refused")
        except SystemExit as e:
            assert "uncommitted changes" in str(e)


def test_vendor_register_legacy_note_phrase_becomes_an_earlier_copy():
    legacy = "| tag | `v0.1.1` — published. Earlier: `v0.1.0` at `ef7fe0e` (2026-10-31), the pilot slice |\n"
    assert vr.earlier_copies(legacy) == [("v0.1.0", "ef7fe0e", "2026-10-31")]
    generated = "## Earlier copies\n\n| tag | commit | copied |\n|---|---|---|\n| `v0.1.0` | `ef7fe0e` | 2026-10-31 |\n"
    assert vr.earlier_copies(generated) == [("v0.1.0", "ef7fe0e", "2026-10-31")]
    assert vr.earlier_copies("| `applications/APP-0001.toml` | `" + "a" * 64 + "` |\n") == [], "a digest row is not an earlier copy"


def test_real_copy_note_is_the_tools_output_at_the_tag():
    """The shipped SOURCE.md is what the tool writes, not a hand-edited table: its marker, its
    tag row, its earlier-copies table and the digest of every file it lists."""
    import hashlib
    dest = ROOT / "kg_experiment" / "demo" / "register"
    note = (dest / "SOURCE.md").read_text(encoding="utf-8")
    assert vr.MARK in note
    assert re.search(r"^\| tag \| `v0\.1\.1` — the demo reads the tag", note, re.M)
    assert "| `v0.1.0` | `ef7fe0e` | 2026-10-31 |" in note
    files = {p.relative_to(dest).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
             for p in dest.rglob("*") if p.is_file() and p.name != "SOURCE.md" and "__pycache__" not in p.parts}
    assert vr.source_note({"commit": "c54f86c3aa470f0a81ec25c00801da35f81398bd", "subject": "Merge pull request #3 from fdurieux/claude/cite-req-06",
                           "date": "2026-11-01", "tag": "v0.1.1", "repo": "fdurieux/ieam-register", "files": sorted(files)},
                          files, "2026-11-01", "2026-10-30", [("v0.1.0", "ef7fe0e", "2026-10-31")]) == note

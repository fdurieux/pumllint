"""Re-vendor the IEAM register under the kg demo from a checkout at a tag.

    python tools/vendor_register.py ../ieam-register               # at the tag the checkout is on
    python tools/vendor_register.py ../ieam-register --dry-run     # say what would change, write nothing

The checkout must be clean and at a tag (``git describe --tags --exact-match``); an untagged
commit needs ``--allow-untagged``, since the demo reads a tag and says so on the page. The tool
copies the register's fixed path set byte for byte into ``kg_experiment/demo/register/``
(deleting what the copy held before) and writes ``SOURCE.md`` from git's own answers: the tag,
the commit and its subject and date, the sha256 of every file copied, the pinned date for the
checker (the newest kit export's date) and the earlier copies carried forward. Nothing is
fetched: the checkout is the maintainer's. ``tests/test_kg_demo.py`` then holds every file to
its digest and runs the vendored checker clean at the pinned date.
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / "kg_experiment" / "demo" / "register"
PATHS = ("metamodel", "glossary", "capabilities", "products", "journeys", "processes", "applications",
         "information", "organisation", "relationships", "exceptions", "mapping", "decisions", "exports/kit",
         "tools/register.py", "tools/check_register.py", "tools/impact.py")
WHAT = ("the metamodel, the glossary, the seven taxonomy directories, the relationship files, the exceptions, "
        "the mapping matrix, the decision records, the kit export folder, and three tools (`register.py`, "
        "`check_register.py`, `impact.py`); nothing else")
MARK = "generated by `tools/vendor_register.py`"


def _git(checkout: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(checkout), *args], check=True, capture_output=True, text=True,
                          encoding="utf-8").stdout.strip()


def _sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def describe(checkout: Path, allow_untagged: bool, paths: tuple[str, ...] = PATHS) -> dict:
    """What git says about the checkout: refuses a dirty tree and, unless allowed, an untagged HEAD.
    ``paths`` is the fixed set to copy; the register's by default, the Legible model's from
    ``tools/vendor_legible_model.py``, which shares this function."""
    if not (checkout / ".git").exists():
        raise SystemExit(f"{checkout} is not a git checkout")
    if _git(checkout, "status", "--porcelain", "--untracked-files=no"):
        raise SystemExit(f"{checkout} has uncommitted changes; the copy must come from a commit")
    commit = _git(checkout, "rev-parse", "HEAD")
    subject, date = _git(checkout, "log", "-1", "--format=%s%n%cs").split("\n", 1)
    try:
        tag = _git(checkout, "describe", "--tags", "--exact-match", "HEAD")
    except subprocess.CalledProcessError:
        if not allow_untagged:
            raise SystemExit(f"{commit[:7]} carries no tag; the demo reads a tag (pass --allow-untagged to copy a commit)")
        tag = ""
    try:
        url = _git(checkout, "remote", "get-url", "origin")
    except subprocess.CalledProcessError:
        url = ""
    m = re.search(r"github\.com[:/]([^/]+/[^/]+?)(?:\.git)?$", url)
    repo = m.group(1) if m else ""
    files = sorted(f for f in _git(checkout, "ls-files", "-z", "--", *paths).split("\0") if f)
    missing = [p for p in paths if not (checkout / p).exists()]
    if missing:
        raise SystemExit(f"the checkout lacks {', '.join(missing)}")
    return {"commit": commit, "subject": subject, "date": date, "tag": tag, "repo": repo, "files": files}


def earlier_copies(note: str) -> list[tuple[str, str, str]]:
    """The earlier copies an existing SOURCE.md records: its own 'Earlier copies' rows, or the
    hand-written note's 'Earlier: `v0.1.0` at `ef7fe0e` (2026-10-31)' phrase."""
    rows = re.findall(r"^\| `([^`|]*)` \| `([0-9a-f]{7,40})` \| (\d{4}-\d{2}-\d{2}) \|$", note, re.M)
    if rows:
        return [(t, c[:7], d) for t, c, d in rows]
    legacy = re.findall(r"`(v[0-9][^`]*)` at `([0-9a-f]{7,40})` \((\d{4}-\d{2}-\d{2})\)", note)
    return [(t, c[:7], d) for t, c, d in legacy]


def current_copy(note: str) -> tuple[str, str, str]:
    tag = re.search(r"^\| tag \| `(v[0-9][^`]*)`", note, re.M)
    commit = re.search(r"\| commit \| `([0-9a-f]{40})`", note)
    copied = re.search(r"^\| copied \| (\d{4}-\d{2}-\d{2})", note, re.M)
    return (tag.group(1) if tag else "", commit.group(1)[:7] if commit else "", copied.group(1) if copied else "")


def source_note(info: dict, digests: dict[str, str], copied: str, pinned: str, earlier: list[tuple[str, str, str]]) -> str:
    tag_cell = (f"`{info['tag']}` — the demo reads the tag; the commit is what it resolves to" if info["tag"]
                else "none — an untagged commit, copied with `--allow-untagged`")
    lines = [
        "# Vendored copy of the IEAM register, at a tag", "",
        "| | |", "|---|---|",
        f"| source repository | `{info['repo'] or 'fdurieux/ieam-register'}` (public test case; synthetic content, the CargoQuote kit) |",
        f"| commit | `{info['commit']}` — \"{info['subject']}\", {info['date']} |",
        f"| tag | {tag_cell} |",
        f"| what is copied | {WHAT} |",
        f"| files | {len(digests)} |",
        f"| copied | {copied}, byte for byte, {MARK} from a clean checkout at that commit |",
        f"| pinned date for the checker | `{pinned}`, the newest kit export's date: an exception's expiry read at the wall clock would change the coverage view under the viewer |",
        "",
        "The demo reads this copy for its register view, footprint and projection",
        "(pumllint `docs/ieam-register-demo-integration.md`); the copy is not fetched",
        "at build time, the image carries it, and the demo never writes to the",
        "register. The register's TOML at the commit is the record of identities,",
        "links, states, approvals and exceptions; this table is the record of which",
        "bytes the demo carries. To refresh it, check the source repository out at",
        "the tag you want and run `python tools/vendor_register.py <checkout>`, which",
        "rewrites this file; `tests/test_kg_demo.py` holds every file to its digest",
        "and runs the vendored checker at the pinned date.",
        "",
        "| file | sha256 |", "|---|---|",
    ]
    lines += [f"| `{rel}` | `{sha}` |" for rel, sha in sorted(digests.items())]
    if earlier:
        lines += ["", "## Earlier copies", "", "| tag | commit | copied |", "|---|---|---|"]
        lines += [f"| `{t}` | `{c}` | {d} |" for t, c, d in earlier]
    return "\n".join(lines) + "\n"


def vendor(checkout: Path, dest: Path = DEST, *, allow_untagged: bool = False, copied: str | None = None,
           pinned: str | None = None, dry_run: bool = False, out=print) -> dict:
    info = describe(checkout, allow_untagged)
    new = {rel: _sha(checkout / rel) for rel in info["files"]}
    old_note = (dest / "SOURCE.md").read_text(encoding="utf-8") if (dest / "SOURCE.md").exists() else ""
    old = {p.relative_to(dest).as_posix(): _sha(p) for p in dest.rglob("*")
           if p.is_file() and p.name != "SOURCE.md" and "__pycache__" not in p.parts} if dest.exists() else {}
    added = sorted(set(new) - set(old))
    removed = sorted(set(old) - set(new))
    changed = sorted(k for k in set(new) & set(old) if new[k] != old[k])
    exports = sorted(re.findall(r"^exports/kit/(\d{4}-\d{2}-\d{2})/", "\n".join(new), re.M))
    pinned = pinned or (exports[-1] if exports else info["date"])
    copied = copied or dt.date.today().isoformat()
    earlier = earlier_copies(old_note)
    cur = current_copy(old_note)
    if cur[1] and cur[1] != info["commit"][:7] and cur[1] not in {c for _, c, _ in earlier}:
        earlier.insert(0, cur)
    note = source_note(info, new, copied, pinned, earlier)
    out(f"{info['repo'] or checkout} at {info['tag'] or 'no tag'} ({info['commit'][:7]}, {info['date']}): "
        f"{len(new)} files; {len(added)} added, {len(removed)} removed, {len(changed)} changed; pinned date {pinned}")
    for label, items in (("added", added), ("removed", removed), ("changed", changed)):
        for rel in items:
            out(f"  {label}: {rel}")
    if not dry_run:
        for rel in old:
            (dest / rel).unlink()
        for d in sorted((p for p in dest.rglob("*") if p.is_dir()), reverse=True) if dest.exists() else []:
            if not any(d.iterdir()):
                d.rmdir()
        for rel in new:
            (dest / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(checkout / rel, dest / rel)
        (dest / "SOURCE.md").write_text(note, encoding="utf-8", newline="\n")
        out(f"wrote {dest / 'SOURCE.md'}")
    return {**info, "digests": new, "added": added, "removed": removed, "changed": changed, "pinned": pinned, "note": note}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("checkout", type=Path, help="a clean checkout of fdurieux/ieam-register at the tag to vendor")
    ap.add_argument("--dest", type=Path, default=DEST, help=f"where the copy lives (default {DEST.relative_to(ROOT).as_posix()})")
    ap.add_argument("--allow-untagged", action="store_true", help="copy a commit that carries no tag")
    ap.add_argument("--date", help="the 'copied' date to record (default today)")
    ap.add_argument("--pinned-date", help="the checker's pinned date (default the newest kit export's)")
    ap.add_argument("--dry-run", action="store_true", help="report what would change and write nothing")
    a = ap.parse_args(argv)
    vendor(a.checkout.resolve(), a.dest.resolve(), allow_untagged=a.allow_untagged, copied=a.date,
           pinned=a.pinned_date, dry_run=a.dry_run)
    return 0


if __name__ == "__main__":
    sys.exit(main())
